const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('worldrenew', Object.freeze({
  onUpdateStatus: callback => { const listener = (_event, value) => callback(value); ipcRenderer.on('updates:changed', listener); return () => ipcRenderer.removeListener('updates:changed', listener); },
  updateStatus: () => ipcRenderer.invoke('updates:status'),
  updateSettings: value => ipcRenderer.invoke('updates:settings', value),
  checkUpdates: () => ipcRenderer.invoke('updates:check'),
  downloadUpdate: () => ipcRenderer.invoke('updates:download'),
  revealUpdate: () => ipcRenderer.invoke('updates:reveal'),
  revealPlacedCopy: () => ipcRenderer.invoke('archive:reveal'),
  saveBuildArchive: () => ipcRenderer.invoke('archive:save'),
  openBuildArchive: () => ipcRenderer.invoke('archive:open'),
  previewBuildArchive: data => ipcRenderer.invoke('archive:preview',data),
  createPlacedCopy: data => ipcRenderer.invoke('archive:place',data),
  chooseTextures: () => ipcRenderer.invoke('textures:choose'),
  loadTextures: palette => ipcRenderer.invoke('textures:load', palette),
  openWorld: () => ipcRenderer.invoke('world:open'),
  rescan: () => ipcRenderer.invoke('world:rescan'),
  saveProtection: protection => ipcRenderer.invoke('project:save', protection),
  preview: (selected, protection, bufferChunks = 1) => ipcRenderer.invoke('plan:preview', { selected, protection, bufferChunks }),
  saveRegenerationReview: reviewDigest => ipcRenderer.invoke('plan:save', reviewDigest),
  exportRegeneration: data => ipcRenderer.invoke('plan:export', data),
  revealRegeneration: () => ipcRenderer.invoke('plan:reveal'),
  createCopy: confirmedClosed => ipcRenderer.invoke('world:copy', confirmedClosed),
  captureBuild: data => ipcRenderer.invoke('build:capture', data),
  listSelections: () => ipcRenderer.invoke('build:selections'),
  saveSelection: name => ipcRenderer.invoke('build:selection-save', name),
  viewSource: data => ipcRenderer.invoke('build:view-source', data),
  viewDestination: data => ipcRenderer.invoke('build:view-destination', data),
  openDestination: () => ipcRenderer.invoke('build:destination'),
  previewTransfer: data => ipcRenderer.invoke('build:preview', data),
  saveTransferPlan: () => ipcRenderer.invoke('build:save'),
  onProgress: callback => { const listener = (_event, progress) => callback(progress); ipcRenderer.on('world:progress', listener); return () => ipcRenderer.removeListener('world:progress', listener); }
}));
