import { _electron as electron } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { makeTerrainWorld } from '../tests/terrain-fixtures.js';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
fs.mkdirSync(path.join(root, 'work'), { recursive: true });
const work = fs.mkdtempSync(path.join(root, 'work/terrain-smoke-'));
const fixture = makeTerrainWorld(path.join(work, 'synthetic-world'));
const snapshot = () => fs.readdirSync(fixture, { recursive: true, withFileTypes: true }).filter(e => e.isFile()).map(e => { const file = path.join(e.parentPath, e.name); return [path.relative(fixture, file), createHash('sha256').update(fs.readFileSync(file)).digest('hex')]; });
const before = snapshot(), env = { ...process.env, WORLDRENEW_USER_DATA: path.join(work, 'profile') }; delete env.ELECTRON_RUN_AS_NODE;
const executablePath = process.env.WORLDRENEW_EXECUTABLE;
const app = await electron.launch({ ...(executablePath ? { executablePath } : {}), args: [...(executablePath ? [] : [root]), `--world=${fixture}`], env, timeout: 30000 });
const errors = [];
try {
  const page = await app.firstWindow(); page.on('pageerror', e => errors.push(e.message));
  await page.click('#open');
  await page.waitForFunction(() => document.getElementById('terrain-status').dataset.ready === '106' && document.getElementById('terrain-status').dataset.failed === '1');
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
  await page.screenshot({ path: path.join(work, 'terrain-overworld.png') });
  const colors = await page.evaluate(() => { const c = document.getElementById('map'), data = c.getContext('2d').getImageData(0, 0, c.width, c.height).data, colors = new Set(); for (let i = 0; i < data.length; i += 4) colors.add(`${data[i]},${data[i+1]},${data[i+2]}`); return colors.size; });
  assert.ok(colors > 50, 'Actual material and height shading must replace flat chunk colors.');
  await page.click('#toggle-protection');
  for (const [id, value] of Object.entries({ x1: -4, z1: 0, x2: -3, z2: 1 })) await page.fill('#' + id, String(value));
  await page.click('#select-area'); assert.equal(await page.textContent('#selection-count'), '4');
  await page.click('#fit-selection');
  await page.screenshot({ path: path.join(work, 'terrain-selection.png') });
  await page.click('#protect'); assert.equal(await page.textContent('#protected-count'), '4');
  await page.click('#save'); await page.waitForFunction(() => document.getElementById('save-state').textContent === 'Plan up to date');
  await page.click('#open-transfer');
  assert.equal(await page.inputValue('#build-minX'), '-64'); assert.equal(await page.inputValue('#build-maxZ'), '31');
  await page.click('#close-build'); await page.click('#toggle-protection');
  await page.click('#fit');
  const map = await page.locator('#map').boundingBox();
  await page.mouse.move(map.x + map.width / 2, map.y + map.height / 2);
  const coordinateBefore = await page.textContent('#coordinates');
  await page.mouse.down({ button: 'right' }); await page.mouse.move(map.x + map.width / 2 + 50, map.y + map.height / 2); await page.mouse.up({ button: 'right' });
  await page.mouse.move(map.x + map.width / 2, map.y + map.height / 2);
  assert.notEqual(await page.textContent('#coordinates'), coordinateBefore);
  await page.click('#zoom-in'); await page.click('#map'); await page.keyboard.press('ArrowRight');
  await page.selectOption('#dimension', { label: 'The Nether · 1 chunks' });
  await page.waitForFunction(() => document.getElementById('terrain-status').dataset.ready === '1');
  assert.equal(await page.inputValue('#terrain-mode'), 'caverns');
  assert.match(await page.textContent('#terrain-note'), /3 air blocks/);
  await page.screenshot({ path: path.join(work, 'terrain-nether-caverns.png') });
  await page.selectOption('#terrain-mode', 'roof');
  await page.waitForFunction(() => document.getElementById('terrain-status').dataset.ready === '1');
  await page.screenshot({ path: path.join(work, 'terrain-nether-roof.png') });
  // Switch while requests are outstanding: stale responses must not cross dimensions.
  await page.selectOption('#terrain-mode', 'surface');
  await page.selectOption('#dimension', { label: 'The End · 1 chunks' });
  await page.waitForFunction(() => document.getElementById('terrain-status').dataset.ready === '1');
  assert.equal(await page.inputValue('#terrain-mode'), 'surface');
  assert.equal(await page.locator('#terrain-mode option[value="caverns"]').count(), 0);
  await page.screenshot({ path: path.join(work, 'terrain-end.png') });
  assert.deepEqual(snapshot(), before, 'Map browsing must not write any source files.'); assert.deepEqual(errors, []);
  const report = { passed: true, checks: ['material detail and relief', 'explicit malformed chunk', 'selection to 3D bounds', 'protection save', 'pan/zoom/coordinates', 'Nether cavern/roof', 'End void', 'stale dimension requests', 'source hashes unchanged'], screenshots: work };
  fs.writeFileSync(path.join(work, 'results.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report, null, 2));
} finally { await app.close(); }
